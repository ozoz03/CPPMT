#pragma once
#include "Point.h"

// ДЗ18: знімок стану дрона, який фізика віддає MissionProcessor'у (копією, під м'ютексом).
struct DroneTelemetry {
    Coord pos;               // поточна позиція
    Coord speed;             // вектор швидкості (vx, vy)
    float timeSecSinceStart; // час останнього оновлення фізики (для компенсації нерівних кроків в аутпуті)
    // Напрямок (курс) не можна надійно відновити з вектора швидкості при нульовій
    // швидкості (стоп/поворот на місці), тож фізика віддає його окремим полем.
    float direction;         // курс дрона, рад
};
